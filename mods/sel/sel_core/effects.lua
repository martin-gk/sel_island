--[[
    effects.lua - sounds, sparkles and fireworks
    ============================================

    Because children should not need to read, all feedback in SEL Island is
    shown with light, particles and sound. These helpers keep that feedback
    consistent across all activities.

    Sounds (generated by a script, in sounds/):
      "sel_core_chime"    - a step was completed (ding-ding)
      "sel_core_success"  - big success (rising arpeggio)
      "sel_core_tick"     - one second of a group countdown
      "sel_core_reset"    - group countdown interrupted
      "sel_core_firework" - firework pop
]]

-- Colours used for particles. Use these names everywhere for consistency.
sel_core.colors = {
	blue   = "#4aa3ff",
	green  = "#5be36b",
	gold   = "#ffd23f",
	purple = "#c77dff",
	orange = "#ff9a3c",
	white  = "#ffffff",
	pink   = "#ff6fb5",
}

-- Play a sound.
--   where = a position table  -> heard nearby (positional)
--   where = a player object   -> heard only by that player
--   where = nil               -> heard by everyone
function sel_core.play(sound, where, gain)
	local params = {gain = gain or 1.0}
	if type(where) == "table" and where.x then
		params.pos = where
		params.max_hear_distance = 32
	elseif where then
		params.to_player = where:get_player_name()
	end
	core.sound_play(sound, params, true) -- true = "fire and forget"
end

-- Particle texture in a given colour (white dot tinted by ^[multiply).
local function spark_texture(color)
	return "sel_core_spark.png^[multiply:" .. color
end

-- A short burst of glowing sparkles around `pos`.
--   color  : hex string, e.g. sel_core.colors.gold
--   amount : number of sparkles (default 24)
function sel_core.sparkle(pos, color, amount)
	core.add_particlespawner({
		amount = amount or 24,
		time = 0.4,
		minpos = vector.offset(pos, -0.6, 0, -0.6),
		maxpos = vector.offset(pos, 0.6, 1.2, 0.6),
		minvel = {x = -0.6, y = 0.6, z = -0.6},
		maxvel = {x = 0.6, y = 1.8, z = 0.6},
		minacc = {x = 0, y = -0.5, z = 0},
		maxacc = {x = 0, y = -0.5, z = 0},
		minexptime = 0.6,
		maxexptime = 1.4,
		minsize = 1.0,
		maxsize = 2.2,
		texture = spark_texture(color or sel_core.colors.gold),
		glow = 14, -- particles glow even in the dark
	})
end

-- Gentle ambient sparkles above a block (used by glowing markers so they
-- catch the eye). Called repeatedly by an ABM in the activity mods.
function sel_core.ambient_sparkle(pos, color)
	core.add_particlespawner({
		amount = 3,
		time = 1,
		minpos = vector.offset(pos, -0.4, 0.5, -0.4),
		maxpos = vector.offset(pos, 0.4, 0.6, 0.4),
		minvel = {x = 0, y = 0.4, z = 0},
		maxvel = {x = 0, y = 0.8, z = 0},
		minexptime = 1.0,
		maxexptime = 1.6,
		minsize = 0.8,
		maxsize = 1.4,
		texture = spark_texture(color),
		glow = 12,
	})
end

-- One firework explosion at `pos`: stars flying out in every direction.
local function firework_burst(pos, color)
	core.add_particlespawner({
		amount = 70,
		time = 0.1,
		minpos = pos,
		maxpos = pos,
		minvel = {x = -6, y = -6, z = -6},
		maxvel = {x = 6, y = 6, z = 6},
		minacc = {x = 0, y = -3, z = 0},
		maxacc = {x = 0, y = -3, z = 0},
		minexptime = 0.8,
		maxexptime = 1.6,
		minsize = 1.5,
		maxsize = 3,
		texture = "sel_core_star.png^[multiply:" .. color,
		glow = 14,
	})
	sel_core.play("sel_core_firework", pos, 0.6)
end

-- Fireworks show above `pos`: several bursts in random colours over about
-- three seconds, plus the success melody. Use for big group achievements.
function sel_core.fireworks(pos, bursts)
	local palette = {"blue", "green", "gold", "purple", "orange", "pink"}
	sel_core.play("sel_core_success", pos, 1.0)
	for i = 1, (bursts or 6) do
		core.after(i * 0.45, function()
			local p = vector.offset(pos,
				math.random(-5, 5), math.random(8, 13), math.random(-5, 5))
			local color = sel_core.colors[palette[math.random(#palette)]]
			firework_burst(p, color)
		end)
	end
end
