--[[
    sel_looks - how the children look
    =================================

    Minetest Game gives every player the same look. In a class that is not
    good enough: children should be able to play as somebody they like to
    be. So there are EIGHT looks with different skin tones, hair and
    clothes (generated by a script).

      * A new child gets one of the looks automatically. Which one depends
        on the name, so a class starts out nicely mixed. (The look with
        a headscarf is only ever chosen, never given - see AUTOMATIC.)
      * At the WARDROBE on the Hub plaza, a right click changes to the next
        look. A small picture shows the new look (children do not see
        themselves in first-person view).
      * The choice is remembered (player metadata "sel_looks:look").

    No look is "for boys" or "for girls": there are no labels, and the
    clothes colours are mixed on purpose. See the Inclusion section of the
    README.
]]

sel_looks = {}
local S = core.get_translator("sel_looks")

sel_looks.COUNT = 8 -- textures sel_looks_1.png ... sel_looks_8.png

-- The looks a child can be GIVEN automatically. Look 7 (with a headscarf)
-- is left out here: it is there for everyone who wants it, but nobody
-- should find themselves wearing one without having chosen it.
sel_looks.AUTOMATIC = {1, 2, 3, 4, 5, 6, 8}
local META_KEY = "sel_looks:look"

-- The look a player starts with: spread over all looks by their name.
local function default_look(name)
	local sum = 0
	for i = 1, #name do
		sum = sum + name:byte(i)
	end
	return sel_looks.AUTOMATIC[sum % #sel_looks.AUTOMATIC + 1]
end

-- Which look does this player have? (1 .. COUNT)
function sel_looks.get(player)
	local look = player:get_meta():get_int(META_KEY)
	if look < 1 or look > sel_looks.COUNT then
		look = default_look(player:get_player_name())
	end
	return look
end

-- Put a look on a player and remember it.
function sel_looks.set(player, look)
	player:get_meta():set_int(META_KEY, look)
	local texture = "sel_looks_" .. look .. ".png"
	-- player_api keeps track of the textures (so they survive e.g. an
	-- animation change); if it does not know this player, set them directly
	if not pcall(player_api.set_textures, player, {texture}) then
		player:set_properties({textures = {texture}})
	end
end

-- Change to the next look and show a small picture of it.
function sel_looks.next(player)
	local look = sel_looks.get(player) % sel_looks.COUNT + 1
	sel_looks.set(player, look)
	sel_core.show_hint(player, "sel_looks_preview_" .. look .. ".png", 2.5)
	sel_core.sparkle(player:get_pos(), sel_core.colors.gold, 20)
	sel_core.play("sel_core_tick", player)
	return look
end

-- Dress every player when they join (a moment after player_api has set
-- its default look).
core.register_on_joinplayer(function(player)
	local name = player:get_player_name()
	core.after(0.2, function()
		local p = core.get_player_by_name(name)
		if p then
			sel_looks.set(p, sel_looks.get(p))
		end
	end)
end)

-- The wardrobe: right click = next look. Unbreakable.
core.register_node("sel_looks:wardrobe", {
	description = S("Wardrobe (right click: change your look)"),
	tiles = {"default_wood.png", "default_wood.png", "sel_looks_wardrobe.png"},
	light_source = 6,
	groups = {sel_unbreakable = 1},
	diggable = false,
	on_blast = function() end,
	sounds = default and default.node_sound_wood_defaults() or nil,
	on_rightclick = function(pos, node, clicker)
		if clicker and clicker:is_player() then
			sel_looks.next(clicker)
		end
	end,
})
