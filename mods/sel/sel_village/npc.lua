--[[
    npc.lua - the people of the village
    ===================================

    The MAYOR (a woman with a plum headscarf and a green coat) stands where
    the gold path arrives. Her three pictures:
      1  the gemstones glow in children's hands
      2  a gemstone becomes a beautiful lamp
      3  the square full of light, everyone happy - and the GOLD pedestal

    The VILLAGE CHILD (smaller, yellow shirt) stands further on, at the
    broken bridge. Four pictures:
      1  my grandparents live on the other side of the water
      2  the way around the lake is very long
      3  a gemstone becomes a bridge plank for the gap
      4  together on the bridge, a heart - and the BLUE pedestal

    The GRANDPARENTS stand in front of their house across the pond. Each
    shows one picture: the family together, with a heart.

    Both stories are deliberately equally warm: there is no "right" side.
    The pictures are generated by a script.
]]

